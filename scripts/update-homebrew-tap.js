// Render the Homebrew formula and cask for a release.
//
//   bun scripts/update-homebrew-tap.js <version> <assets-dir> --out <dir>
//
// <assets-dir> is the publish job's release-assets directory; the .sha256 files
// it holds are the checksums the formula and cask should declare. <dir> is a
// checkout of jolo-build/homebrew-tap (or deploy/homebrew/ to refresh the
// in-repo copies).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";

const [version, assetsDir, ...rest] = process.argv.slice(2);
const outFlag = rest.indexOf("--out");
if (!/^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$/.test(version ?? "") || !assetsDir || outFlag === -1 || !rest[outFlag + 1]) {
  console.error("usage: bun scripts/update-homebrew-tap.js <version> <assets-dir> --out <dir>");
  process.exit(64);
}
const outDir = rest[outFlag + 1];

function sha256For(name) {
  const file = path.join(assetsDir, `${name}.sha256`);
  const [sum, entry] = readFileSync(file, "utf8").trim().split(/\s+/);
  if (!/^[0-9a-f]{64}$/.test(sum ?? "") || entry !== name) throw new Error(`Invalid checksum file for ${name}`);
  return sum;
}

const cli = Object.fromEntries(
  ["darwin-arm64", "darwin-x64", "linux-arm64", "linux-x64"].map(t => [t, sha256For(`jolo-cli-${t}.tar.gz`)]),
);
const dmg = Object.fromEntries(
  ["arm64", "x64"].map(a => [a, sha256For(`jolo-desktop-darwin-${a}.dmg`)]),
);

const formula = `# Generated by scripts/update-homebrew-tap.js — edit the script, not this file.
class JoloCli < Formula
  desc "Terminal CLI for working with coding agents"
  homepage "https://jolo.build"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
      url "https://github.com/jolo-build/jolo/releases/download/v#{version}/jolo-cli-darwin-arm64.tar.gz"
      sha256 "${cli["darwin-arm64"]}"
    end
    on_intel do
      url "https://github.com/jolo-build/jolo/releases/download/v#{version}/jolo-cli-darwin-x64.tar.gz"
      sha256 "${cli["darwin-x64"]}"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/jolo-build/jolo/releases/download/v#{version}/jolo-cli-linux-arm64.tar.gz"
      sha256 "${cli["linux-arm64"]}"
    end
    on_intel do
      url "https://github.com/jolo-build/jolo/releases/download/v#{version}/jolo-cli-linux-x64.tar.gz"
      sha256 "${cli["linux-x64"]}"
    end
  end

  def install
    libexec.install Dir["*"]
    bin.install_symlink libexec/"bin/jolo"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/jolo --version")
  end
end
`;

const cask = `# Generated by scripts/update-homebrew-tap.js — edit the script, not this file.
cask "jolo" do
  version "${version}"

  arch arm: "arm64", intel: "x64"

  sha256 arm:   "${dmg["arm64"]}",
         intel: "${dmg["x64"]}"

  url "https://github.com/jolo-build/jolo/releases/download/v#{version}/jolo-desktop-darwin-#{arch}.dmg"
  name "Jolo"
  desc "Desktop app for working with coding agents"
  homepage "https://jolo.build"

  app "Jolo.app"

  zap trash: [
    "~/Library/Application Support/Jolo",
    "~/Library/Caches/jolo",
    "~/Library/Preferences/dev.jolo.desktop.plist",
    "~/Library/Saved Application State/dev.jolo.desktop.savedState",
  ]
end
`;

mkdirSync(path.join(outDir, "Formula"), { recursive: true });
mkdirSync(path.join(outDir, "Casks"), { recursive: true });
writeFileSync(path.join(outDir, "Formula", "jolo-cli.rb"), formula);
writeFileSync(path.join(outDir, "Casks", "jolo.rb"), cask);
console.log(`Rendered jolo-cli.rb and jolo.rb for v${version} into ${outDir}`);
